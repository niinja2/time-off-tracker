CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    name          VARCHAR(100) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    admin         BOOLEAN      NOT NULL DEFAULT FALSE,
    hire_date     DATE         NOT NULL
);

CREATE TABLE teams (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(100) NOT NULL UNIQUE,
    lead_id BIGINT       NOT NULL REFERENCES users (id)
);

CREATE TABLE team_members (
    team_id BIGINT NOT NULL REFERENCES teams (id),
    user_id BIGINT NOT NULL REFERENCES users (id),
    PRIMARY KEY (team_id, user_id)
);

CREATE TABLE time_off_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id         BIGINT       NOT NULL REFERENCES users (id),
    type             VARCHAR(20)  NOT NULL CHECK (type IN ('VACATION', 'SICK_LEAVE', 'DAY_OFF')),
    start_date       DATE         NOT NULL,
    end_date         DATE         NOT NULL,
    reason           VARCHAR(500),
    status           VARCHAR(20)  NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    decision_comment VARCHAR(500),
    decided_by_id    BIGINT REFERENCES users (id),
    decided_at       TIMESTAMPTZ,
    cancel_reason    VARCHAR(500),
    cancelled_by_id  BIGINT REFERENCES users (id),
    cancelled_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL,
    -- R8: the end date can't be before the start date
    CHECK (end_date >= start_date)
);
